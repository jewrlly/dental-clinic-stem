"""
Параметри моделі стоматологічної клініки
"""
import numpy as np
import pandas as pd
 
# ---------------------------------------------------------------- модельний час
DAYS = 5                                       # робочий тиждень (пн–пт)
WORK_HOURS = [9, 10, 11, 12, 14, 15, 16, 17]   # 09:00–18:00, перерва 13:00–14:00
HOURS_PER_DAY = len(WORK_HOURS)                # 8 робочих годин
N_STEPS = DAYS * HOURS_PER_DAY                 # 40 кроків по 1 год (лише робочі години)
 
# ---------------------------------------------------------------- система
QUEUE_LIMIT = 4        # місць у залі очікування (місткість черги)
SALARY = 3000          # зарплата стоматолога за зміну (день), грн
N_RUNS = 100           # кількість прогонів для методу Монте-Карло
MAX_DOCTORS = 8        # перебираємо 1..MAX_DOCTORS стоматологів
 
# ---------------------------------------------------------------- відключення
P_OUTAGE = 0.05        # ймовірність відключення світла/води протягом дня
OUTAGE_HOURS = (3, 4)  # тривалість відключення, год
 
# ---------------------------------------------------------------- потік клієнтів
# Кількість клієнтів за годину ~ Пуассон(lambda), lambda залежить від періоду дня
PERIODS = [            # (початок, кінець, lambda клієнтів/год)
    (9, 11, 3.0),      # ранок – помірний потік
    (11, 13, 4.0),     # до обіду – пік
    (14, 16, 3.0),     # після обіду – спад
    (16, 18, 5.0),     # після робочого дня – найбільший потік
]
 
# ---------------------------------------------------------------- послуги
SERVICES = pd.DataFrame({
    "Послуга": ["Огляд і консультація", "Лікування карієсу", "Професійна чистка",
                "Видалення зуба", "Встановлення коронки"],
    "p":    [0.35, 0.30, 0.15, 0.12, 0.08],   # ймовірність замовлення
    "Ціна": [400, 1500, 1200, 1000, 5000],    # грн
    "Час":  [0.5, 1.0, 1.0, 0.75, 2.0],       # середня тривалість, год (Exp)
})
 
MEAN_SERVICE = float((SERVICES.p * SERVICES["Час"]).sum())   # 0.875 год
MEAN_PRICE = float((SERVICES.p * SERVICES["Ціна"]).sum())    # 1290 грн
LAMBDA_AVG = sum((b - a) * l for a, b, l in PERIODS) / HOURS_PER_DAY  # 3.75
 
 
def lam_at(hour):
    """Інтенсивність потоку клієнтів для заданої години."""
    for a, b, l in PERIODS:
        if a <= hour < b:
            return l
    return 0.0
 
 
def outage_plan(rng):
    """Масив з N_STEPS значень True/False: чи є відключення на кроці.
    Кожного дня з ймовірністю P_OUTAGE стається відключення на 3–4 год."""
    plan = np.zeros(N_STEPS, dtype=bool)
    for d in range(DAYS):
        if rng.random() < P_OUTAGE:
            dur = rng.integers(OUTAGE_HOURS[0], OUTAGE_HOURS[1] + 1)
            start = rng.integers(0, HOURS_PER_DAY - dur + 1)
            plan[d * HOURS_PER_DAY + start: d * HOURS_PER_DAY + start + dur] = True
    return plan
 
 
def new_client(rng, step):
    """Генерує одного клієнта: (момент приходу, номер послуги, тривалість)."""
    s = rng.choice(len(SERVICES), p=SERVICES.p)
    dur = rng.exponential(SERVICES["Час"].iat[s])
    t_arr = step + rng.random()          # випадковий момент у межах години
    return t_arr, s, dur